ALTO = 7
ANCHO = 5


def ancho(texto, esc=1, espacio=1):
    """Los pixeles que ocupara `texto`, para poder centrarlo."""
    return len(texto) * (ANCHO + espacio) * esc - espacio * esc


def escribe(pon, x, y, texto, color, esc=1, espacio=1):
    """Escribe con `pon(x, y, color)`, que es lo unico que hace falta del
    lienzo. Devuelve la X donde acaba."""
    cx = x
    for ch in texto:
        g = _F.get(ch, _F.get(ch.upper(), _F[" "]))
        for f in range(ALTO):
            fila = g[f]
            for c in range(ANCHO):
                if fila[c] == "1":
                    for a in range(esc):
                        for b in range(esc):
                            pon(cx + c * esc + b, y + f * esc + a, color)
        cx += (ANCHO + espacio) * esc
    return cx
